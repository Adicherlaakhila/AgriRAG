-- AgriRAG Supabase PostgreSQL schema
-- Run in Supabase Dashboard > SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.farmer_profiles (
  id uuid primary key default gen_random_uuid(),
  name text not null default 'Farmer',
  district text not null,
  crop text not null,
  season text not null,
  soil_type text not null,
  land_acres numeric(10,2) not null check (land_acres > 0),
  preferred_language text not null check (preferred_language in ('English','Telugu','Hindi')),
  created_at timestamptz not null default now()
);

create table if not exists public.knowledge_chunks (
  id bigint generated by default as identity primary key,
  crop text not null,
  guide_title text not null,
  section text not null,
  content text not null,
  source_url text not null,
  keywords text default '',
  dosage_approved boolean not null default false,
  created_at timestamptz not null default now(),
  unique(guide_title, section)
);

create table if not exists public.pest_records (
  id bigint generated by default as identity primary key,
  crop text not null,
  pest text not null,
  symptoms text not null,
  management text not null,
  guide_reference text not null,
  unique(crop,pest)
);

create table if not exists public.weather_samples (
  id bigint generated by default as identity primary key,
  district text not null,
  date date not null,
  rain_mm numeric(7,2) not null,
  tmax_c numeric(5,2) not null,
  tmin_c numeric(5,2) not null,
  relative_humidity_pct integer not null,
  unique(district,date)
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  farmer_id uuid not null references public.farmer_profiles(id) on delete cascade,
  role text not null check (role in ('user','assistant')),
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_knowledge_crop on public.knowledge_chunks(crop);
create index if not exists idx_pest_crop on public.pest_records(crop);
create index if not exists idx_weather_district_date on public.weather_samples(district,date);
create index if not exists idx_chat_farmer_created on public.chat_messages(farmer_id,created_at);

-- Row Level Security
alter table public.farmer_profiles enable row level security;
alter table public.knowledge_chunks enable row level security;
alter table public.pest_records enable row level security;
alter table public.weather_samples enable row level security;
alter table public.chat_messages enable row level security;

-- Classroom / assignment policies for the anon key.
-- These are NOT suitable for production with real farmer PII.
-- Replace with Supabase Auth + owner-based policies before real use.
drop policy if exists "public read knowledge" on public.knowledge_chunks;
create policy "public read knowledge" on public.knowledge_chunks
  for select to anon, authenticated using (true);

drop policy if exists "public read pests" on public.pest_records;
create policy "public read pests" on public.pest_records
  for select to anon, authenticated using (true);

drop policy if exists "public read weather" on public.weather_samples;
create policy "public read weather" on public.weather_samples
  for select to anon, authenticated using (true);

drop policy if exists "anon insert profiles" on public.farmer_profiles;
create policy "anon insert profiles" on public.farmer_profiles
  for insert to anon, authenticated with check (true);

drop policy if exists "anon select profiles" on public.farmer_profiles;
create policy "anon select profiles" on public.farmer_profiles
  for select to anon, authenticated using (true);

drop policy if exists "anon insert chat" on public.chat_messages;
create policy "anon insert chat" on public.chat_messages
  for insert to anon, authenticated with check (true);

drop policy if exists "anon select chat" on public.chat_messages;
create policy "anon select chat" on public.chat_messages
  for select to anon, authenticated using (true);

